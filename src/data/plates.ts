function shot(list: Recipe[]): Recipe[] {
  const order: Record<Recipe["slot"], number> = { Drink: 0, Breakfast: 1, Snack: 2, Dinner: 3 };
  return list
    .map((recipe) => ({ ...recipe, image: recipe.image || SHOTS[recipe.id] || "/graphics/bowl.jpg" }))
    .sort((a, b) => order[a.slot] - order[b.slot]);
}

export function recipesFor(tags: Tags, stageId: StageId): Recipe[] {
  const kitchen = kitchenFor(tags);
  if (stageId.startsWith("p")) return shot(PREGNANCY[kitchen]);
  if (stageId === "b15" || stageId === "b6m" || stageId === "b9") return shot(TODDLER[kitchen]);
  return shot(PARENT[kitchen]);
}
